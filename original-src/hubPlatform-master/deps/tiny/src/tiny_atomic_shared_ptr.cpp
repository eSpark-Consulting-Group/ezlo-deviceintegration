#include <tiny/tiny_atomic_shared_ptr.h>
#include <tiny/tiny_multithreading.h>

namespace tiny {

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

static tiny::multithreading::recursive_mutex_type* g_pRefMutex = nullptr;

tiny::multithreading::recursive_mutex_type& get_ref_mtx() {
    if( !g_pRefMutex )
        g_pRefMutex = new tiny::multithreading::recursive_mutex_type( "RMTX-ATOMIC-SHARED-GLOBAL" );
    return ( *g_pRefMutex );
}

void done_ref_mtx() {
    if( g_pRefMutex ) {
        delete g_pRefMutex;
        g_pRefMutex = nullptr;
    }
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

};  // namespace tiny
