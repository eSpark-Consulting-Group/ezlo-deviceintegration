inline std::ostream& operator<<( std::ostream& os, const SunState::Time& p ) {
    os << std::setfill( '0' );
    os << std::setw( 2 ) << p.hours << ":" << std::setw( 2 ) << p.minutes << ":";

    if( p.seconds != SunState::NaN )
        os << std::setw( 2 ) << p.seconds;
    else
        os << "NaN";
    return os;
}
